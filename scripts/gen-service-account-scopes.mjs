#!/usr/bin/env node
/**
 * Generates src/core/service-account-scopes.ts: the scopes the service-account key asks for (SERVICE_ACCOUNT_SCOPES in
 * src/core/auth.ts), from config/products.json and the scopes the products' methods declare.
 *
 * Each product of the service-account group says which scopes the key gets for it, in "serviceAccountScopes":
 *   "methods"      every scope its methods declare: the generated and curated tools and the gateway methods, as
 *                  requirementsFor (src/core/scopes.ts) counts them for a login (Discovery snapshots and the catalog);
 *   [scope, ...]   exactly these scopes.
 * The key's list is the union, sorted. Only https:// scopes are taken (Discovery also lists bare names such as openid).
 *
 * Needs a compiled dist/ (npx tsc -p tsconfig.json): it reads requirementsFor from there. Run it after a product of the
 * group changes its APIs. With --check it writes nothing and exits 1 when the file is stale (tests/service-account-
 * scopes.test.mjs runs that).
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src', 'core', 'service-account-scopes.ts');
const GROUP = 'service-account';
const check = process.argv.includes('--check');

/**
 * The scopes the key gets, per product of the group and in all, from products.json and the products' methods.
 * perServer is the same lists keyed by the product's server name: a server's token asks for its own list only.
 */
export async function deriveServiceAccountScopes(root = ROOT) {
  const products = JSON.parse(readFileSync(join(root, 'config', 'products.json'), 'utf8')).products;
  const { requirementsFor } = await import(pathToFileURL(join(root, 'dist', 'core', 'scopes.js')).href);
  const { loadConfig } = await import(pathToFileURL(join(root, 'dist', 'core', 'config.js')).href);
  // An empty token folder: the requirements read no login.
  const tokenDir = mkdtempSync(join(tmpdir(), 'gsm-sa-scopes-'));
  try {
    const cfg = loadConfig({ GSM_TOKEN_DIR: tokenDir });
    const perProduct = {};
    const perServer = {};
    for (const [id, p] of Object.entries(products)) {
      if (p.group !== GROUP) continue;
      const rule = p.serviceAccountScopes;
      let scopes;
      if (rule === 'methods') {
        const reqs = await requirementsFor([p.server.name], cfg, { warn: () => undefined });
        scopes = reqs.flatMap((r) => r.scopes);
      } else if (Array.isArray(rule) && rule.length > 0 && rule.every((s) => typeof s === 'string')) {
        scopes = rule;
      } else {
        throw new Error(`product ${id}: serviceAccountScopes must be "methods" or a non-empty list of scope URLs`);
      }
      perProduct[id] = [...new Set(scopes.filter((s) => s.startsWith('https://')))].sort();
      perServer[p.server.name] = perProduct[id];
    }
    const all = [...new Set(Object.values(perProduct).flat())].sort();
    return { perProduct, perServer, all };
  } finally {
    rmSync(tokenDir, { recursive: true, force: true });
  }
}

function source(perProduct, perServer, all) {
  const lines = [
    '/**',
    ' * GENERATED by scripts/gen-service-account-scopes.mjs. Do not edit: change config/products.json (serviceAccountScopes)',
    ' * or the products\' APIs, compile, and run the script again.',
    ' *',
    ' * The scopes the service-account key asks for (SERVICE_ACCOUNT_SCOPES in src/core/auth.ts): the union of what each',
    ' * product of the service-account group declares in "serviceAccountScopes" ("methods": every scope its methods declare).',
    ' * Per product:',
  ];
  for (const [id, scopes] of Object.entries(perProduct)) lines.push(` *   ${id}: ${scopes.map((s) => s.replace('https://www.googleapis.com/auth/', '')).join(', ')}`);
  lines.push(' */');
  lines.push('export const SERVICE_ACCOUNT_KEY_SCOPES: readonly string[] = [');
  for (const s of all) lines.push(`  '${s}',`);
  lines.push('];');
  lines.push('');
  lines.push('/**');
  lines.push(' * The same lists per server of the group (serviceAccountScopesFor in src/core/auth.ts): a server\'s token asks for its');
  lines.push(' * own product\'s scopes only, so a scope Google refuses for one product does not stop the other.');
  lines.push(' */');
  lines.push('export const SERVICE_ACCOUNT_SCOPES_BY_SERVER: Readonly<Record<string, readonly string[]>> = {');
  for (const server of Object.keys(perServer).sort()) {
    lines.push(`  ${server}: [`);
    for (const s of perServer[server]) lines.push(`    '${s}',`);
    lines.push('  ],');
  }
  lines.push('};');
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { perProduct, perServer, all } = await deriveServiceAccountScopes();
  const text = source(perProduct, perServer, all);
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // Not written yet.
  }
  if (check) {
    if (current !== text) {
      console.error('src/core/service-account-scopes.ts is stale: run npx tsc -p tsconfig.json, then node scripts/gen-service-account-scopes.mjs');
      process.exit(1);
    }
    console.log(`src/core/service-account-scopes.ts is up to date: ${all.length} scopes`);
  } else {
    writeFileSync(OUT, text, 'utf8');
    console.log(`wrote src/core/service-account-scopes.ts: ${all.length} scopes`);
  }
}
