#!/usr/bin/env node
/**
 * Generates config/servers.json from config/products.json, the single source of truth.
 *
 * One product is one plugin and one MCP server (the product id is both the plugin name and
 * the server name). The generated map lists, per server, its auth group, its curated module
 * (a file under src/servers, or null), its per-method Discovery APIs and its gateway APIs.
 *
 * Usage: node scripts/gen-servers.mjs
 * Checks before writing: product ids are lowercase letters, every group is known, every
 * curated module is mapped to a file that exists, and no API.version is generated by two
 * products. The unassigned catalog APIs are reported (not an error).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PRODUCTS_FILE = join(ROOT, 'config', 'products.json');
const OUT_FILE = join(ROOT, 'config', 'servers.json');
const CATALOG_FILE = join(ROOT, 'data', 'catalog.json');

/** The seven auth groups. Each has one login; a plugin's login covers only its own servers. */
const GROUPS = {
  cloud: 'Application Default Credentials or an OAuth user token with the cloud-platform scope',
  'workspace-user': 'OAuth user token for Gmail, Drive, Calendar and the other personal Workspace APIs',
  'workspace-admin': 'Service account with domain-wide delegation, impersonating a super admin',
  'service-account': 'Service account key for Google Play and Merchant Center (no user login)',
  searchconsole: 'OAuth user token with the webmasters scope',
  business: 'OAuth user token with the scopes of the business APIs',
  developer: 'OAuth user token with the scopes of the developer platform APIs',
  apikey: 'API key for public APIs that take no sign-in (set with setup-apikey)',
};

/**
 * products.json names curated modules by short name. This table maps each name to the file
 * under src that defines the server's buildTools. A name not in the table is an error.
 */
const CURATED_FILES = {
  cloud: 'src/servers/cloud.ts',
  drive: 'src/servers/gdrive.ts',
  gmail: 'src/servers/gmail.ts',
  calendar: 'src/servers/gcalendar.ts',
  admin: 'src/servers/workspace-admin.ts',
  'search-console': 'src/servers/searchconsole.ts',
  ads: 'src/servers/gads.ts',
  chat: 'src/servers/gchat.ts',
  contacts: 'src/servers/gcontacts.ts',
  classroom: 'src/servers/gclassroom.ts',
};

const ID_PATTERN = /^[a-z]+$/;

function fail(message) {
  console.error(`gen-servers: ${message}`);
  process.exitCode = 1;
  throw new Error(message);
}

function readJson(file) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

/**
 * API references of one list. A generated entry may carry "include": the resource or method paths whose
 * methods become tools (see DiscoverySource.include in src/core/discovery/tools.ts). A gateway entry may not.
 */
function apiRefs(list, where, allowInclude = false) {
  if (!Array.isArray(list)) fail(`${where} must be a list`);
  return list.map((entry) => {
    if (typeof entry?.api !== 'string' || typeof entry?.version !== 'string') {
      fail(`${where} has an entry without api and version: ${JSON.stringify(entry)}`);
    }
    const ref = { api: entry.api, version: entry.version };
    if (entry.include !== undefined) {
      const ok = Array.isArray(entry.include) && entry.include.length > 0 && entry.include.every((p) => typeof p === 'string' && p !== '');
      if (!allowInclude) fail(`${where}: ${entry.api}.${entry.version} may not have include (only generated entries can)`);
      if (!ok) fail(`${where}: ${entry.api}.${entry.version} include must be a non-empty list of paths`);
      ref.include = entry.include;
    }
    return ref;
  });
}

const PROFILE_NAMES = ['readonly', 'readwrite', 'full'];
const PART_PATTERN = /^[a-z][a-z0-9-]*$/;

/**
 * A product's scopePolicy (ScopePolicy in src/core/registry.ts), checked and copied as is. onlyIn maps a scope URL to the
 * profiles that may request it (an empty list: none). optional maps a part name to APIs of the product.
 */
function scopePolicyOf(policy, id, apiNames) {
  if (policy === undefined) return undefined;
  const where = `product ${id} scopePolicy`;
  if (typeof policy !== 'object' || policy === null || Array.isArray(policy)) fail(`${where} must be an object`);
  for (const key of Object.keys(policy)) if (key !== 'onlyIn' && key !== 'optional') fail(`${where} has an unknown key "${key}"`);
  for (const [scope, profiles] of Object.entries(policy.onlyIn ?? {})) {
    if (!scope.startsWith('https://')) fail(`${where}.onlyIn: "${scope}" is not a scope URL`);
    if (!Array.isArray(profiles) || !profiles.every((p) => PROFILE_NAMES.includes(p))) {
      fail(`${where}.onlyIn["${scope}"] must be a list of profiles (${PROFILE_NAMES.join(', ')})`);
    }
  }
  for (const [name, apis] of Object.entries(policy.optional ?? {})) {
    if (!PART_PATTERN.test(name)) fail(`${where}.optional: "${name}" must be lowercase letters, digits or dashes`);
    if (!Array.isArray(apis) || apis.length === 0 || !apis.every((a) => apiNames.has(a))) {
      fail(`${where}.optional["${name}"] must list APIs of the product (${[...apiNames].join(', ')})`);
    }
  }
  return policy;
}

/** Toolsets a product may list by name (LISTED_TOOLSETS in src/core/toolset.ts). all and curated are implicit. */
const LISTED_TOOLSETS = ['google'];
const IMPLICIT_TOOLSETS = ['all', 'curated'];
const TOOL_NAME_PATTERN = /^[a-z0-9_]+$/;

/**
 * A product's toolsets: per listed toolset, { tools, matches, notes?, source? }. tools are the tool names the toolset keeps
 * (a test checks each exists in the plugin's tool map). matches names, per tool, the official Google tools it stands for;
 * an empty list needs a note that says why the tool is kept. Returns { google: [names] } for config/servers.json, or
 * undefined when the product lists none.
 */
function toolsetsOf(value, id) {
  if (value === undefined) return undefined;
  const where = `product ${id} toolsets`;
  if (typeof value !== 'object' || value === null || Array.isArray(value)) fail(`${where} must be an object`);
  const out = {};
  for (const [name, entry] of Object.entries(value)) {
    if (IMPLICIT_TOOLSETS.includes(name)) fail(`${where}: "${name}" is implicit and cannot be listed (${name === 'all' ? 'every tool' : 'derived from the tool origins'})`);
    if (!LISTED_TOOLSETS.includes(name)) fail(`${where}: unknown toolset "${name}" (listed toolsets: ${LISTED_TOOLSETS.join(', ')})`);
    const at = `${where}.${name}`;
    if (typeof entry !== 'object' || entry === null || Array.isArray(entry)) fail(`${at} must be an object with tools and matches`);
    for (const key of Object.keys(entry)) if (!['tools', 'matches', 'notes', 'source'].includes(key)) fail(`${at} has an unknown key "${key}"`);
    const tools = entry.tools;
    if (!Array.isArray(tools) || tools.length === 0 || !tools.every((t) => typeof t === 'string' && TOOL_NAME_PATTERN.test(t))) {
      fail(`${at}.tools must be a non-empty list of tool names`);
    }
    if (new Set(tools).size !== tools.length) fail(`${at}.tools lists a tool twice`);
    const matches = entry.matches ?? {};
    const notes = entry.notes ?? {};
    if (typeof matches !== 'object' || Array.isArray(matches)) fail(`${at}.matches must be an object`);
    if (typeof notes !== 'object' || Array.isArray(notes)) fail(`${at}.notes must be an object`);
    for (const key of [...Object.keys(matches), ...Object.keys(notes)]) {
      if (!tools.includes(key)) fail(`${at}: "${key}" has a match or a note but is not in tools`);
    }
    for (const tool of tools) {
      const m = matches[tool];
      if (!Array.isArray(m) || !m.every((x) => typeof x === 'string' && x !== '')) fail(`${at}.matches["${tool}"] must list the official tools it matches`);
      if (m.length === 0 && (typeof notes[tool] !== 'string' || notes[tool] === '')) fail(`${at}: "${tool}" matches no official tool, so it needs a note`);
    }
    // source: the page of Google's server (a URL), or a list of pages when several of Google's servers make up the
    // product. A product with no official server (every tool matches nothing) says so in text instead.
    const noOfficial = tools.every((tool) => matches[tool].length === 0);
    const isUrl = (s) => typeof s === 'string' && s.startsWith('https://');
    if (entry.source !== undefined) {
      const ok = Array.isArray(entry.source)
        ? entry.source.length > 0 && entry.source.every(isUrl)
        : isUrl(entry.source) || (noOfficial && typeof entry.source === 'string' && entry.source.trim() !== '');
      if (!ok) fail(`${at}.source must be a URL or a list of URLs${noOfficial ? ', or text that says there is no official server' : ''}`);
    }
    out[name] = [...tools];
  }
  return Object.keys(out).length > 0 ? out : undefined;
}

function kindOf(curated, apis) {
  if (curated && apis.length) return 'curated+discovery';
  if (curated) return 'curated';
  if (apis.length) return 'discovery';
  return 'gateway';
}

function main() {
  const products = readJson(PRODUCTS_FILE).products;
  if (!products || typeof products !== 'object') fail('config/products.json has no products object');

  const plugins = {};
  const servers = [];
  const generatedOwner = new Map();

  for (const [id, p] of Object.entries(products)) {
    if (!ID_PATTERN.test(id)) fail(`product id "${id}" must be lowercase letters only`);
    if (!GROUPS[p.group]) fail(`product ${id} has unknown group "${p.group}"`);
    if (typeof p.server?.name !== 'string' || !ID_PATTERN.test(p.server.name)) fail(`product ${id} needs server.name`);

    let curated = null;
    if (p.server.curated !== null && p.server.curated !== undefined) {
      const file = CURATED_FILES[p.server.curated];
      if (!file) fail(`product ${id}: curated module "${p.server.curated}" has no file in CURATED_FILES`);
      if (!existsSync(join(ROOT, file))) fail(`product ${id}: ${file} does not exist`);
      curated = file;
    }

    const apis = apiRefs(p.generated, `product ${id} generated`, true);
    const gatewayApis = apiRefs(p.gateway ?? [], `product ${id} gateway`);
    for (const a of apis) {
      const key = `${a.api}.${a.version}`;
      const owner = generatedOwner.get(key);
      if (owner && owner !== id) fail(`${key} is generated by both ${owner} and ${id}`);
      generatedOwner.set(key, id);
    }

    plugins[id] = p.description;
    const server = {
      name: p.server.name,
      plugin: id,
      group: p.group,
      kind: kindOf(curated, apis),
      curated,
      apis,
    };
    if (gatewayApis.length) server.gatewayApis = gatewayApis;
    // Only a product with a scope policy gets the key, so the entries of the others stay as they were.
    const policy = scopePolicyOf(p.scopePolicy, id, new Set([...apis, ...gatewayApis].map((a) => a.api)));
    if (policy) server.scopePolicy = policy;
    // Only a product that lists a toolset gets the key, so the entries of the others stay as they were.
    const toolsets = toolsetsOf(p.toolsets, id);
    if (toolsets) server.toolsets = toolsets;
    server.label = `${p.title}: ${p.description}`;
    servers.push(server);
  }

  if (servers.length !== 23) console.warn(`gen-servers: expected 23 products, found ${servers.length}`);

  const usedGroups = new Set(servers.map((s) => s.group));
  const map = {
    $comment: 'Generated by scripts/gen-servers.mjs from config/products.json. Do not edit by hand: run node scripts/gen-servers.mjs.',
    plugins,
    groups: GROUPS,
    servers,
  };
  writeFileSync(OUT_FILE, `${JSON.stringify(map, null, 2)}\n`, 'utf8');

  // Report: catalog APIs that no product uses, and product APIs the catalog lacks.
  const assigned = new Set([...generatedOwner.keys()]);
  for (const s of servers) for (const g of s.gatewayApis ?? []) assigned.add(`${g.api}.${g.version}`);
  const unusedGroups = Object.keys(GROUPS).filter((g) => !usedGroups.has(g));

  if (existsSync(CATALOG_FILE)) {
    const catalog = readJson(CATALOG_FILE);
    const catalogKeys = new Set(catalog.apis.map((a) => `${a.name}.${a.version}`));
    const unassigned = [...catalogKeys].filter((k) => !assigned.has(k));
    const missing = [...assigned].filter((k) => !catalogKeys.has(k) && !generatedOwner.has(k));
    console.log(`catalog APIs not assigned to any product: ${unassigned.length}`);
    if (unassigned.length) console.log(`  ${unassigned.slice(0, 40).join(', ')}${unassigned.length > 40 ? ' ...' : ''}`);
    if (missing.length) console.log(`gateway APIs missing from data/catalog.json: ${missing.join(', ')}`);
  }
  console.log(`Wrote config/servers.json: ${Object.keys(plugins).length} plugins, ${servers.length} servers, ${generatedOwner.size} generated APIs.`);
  if (unusedGroups.length) console.log(`Groups with no product: ${unusedGroups.join(', ')}`);
}

try {
  main();
} catch {
  process.exitCode = 1;
}
