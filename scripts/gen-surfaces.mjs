#!/usr/bin/env node
/**
 * Writes docs/SURFACES.md from the real state of the repo: the product map, the catalog,
 * the built plugins and the CLI's own help text. Run after `npm run build` so the tool
 * counts are the built ones.
 *
 * Usage: node scripts/gen-surfaces.mjs
 *        node scripts/gen-surfaces.mjs --check   exit 1 when docs/SURFACES.md would change (writes nothing)
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (rel) => JSON.parse(readFileSync(join(root, rel), 'utf8'));

const products = readJson('config/products.json');
const catalog = readJson('data/catalog.json');
const servers = readJson('config/servers.json');
const marketplace = readJson('.claude-plugin/marketplace.json');

const LOGIN = {
  cloud: { group: 'cloud', setup: 'Desktop OAuth client, then `login cloud`' },
  searchconsole: { group: 'searchconsole', setup: 'Desktop OAuth client, then `login searchconsole`' },
  'workspace-user': { group: 'workspace-user', setup: 'Desktop OAuth client, then `login workspace-user`' },
  'workspace-admin': { group: 'workspace-admin', setup: 'Service account with domain-wide delegation, then `setup-admin`' },
  'service-account': { group: 'service-account', setup: 'Service account key, then `setup-service-account` (no login)' },
  business: { group: 'business', setup: 'Desktop OAuth client, then `login business`' },
  developer: { group: 'developer', setup: 'Desktop OAuth client, then `login developer`' },
  apikey: { group: 'apikey', setup: 'API key, then `setup-apikey` (no login)' },
};

// The tools a server registers (src/core/runtime-tools.ts, the rule the skills and docs/CAPABILITIES.md count with).
const runtimeModule = join(root, 'dist', 'core', 'runtime-tools.js');
if (!existsSync(runtimeModule)) {
  console.error('dist/core/runtime-tools.js is missing. Run npm run build (or npx tsc -p tsconfig.json) first.');
  process.exit(1);
}
const { registersEntry } = await import(pathToFileURL(runtimeModule).href);
const { SERVICE_ACCOUNT_SCOPES_BY_SERVER } = await import(pathToFileURL(join(root, 'dist', 'core', 'service-account-scopes.js')).href);

/** The tools the product's server registers: its tool map without the entries it never registers (registersEntry). */
function toolCount(id) {
  const file = join(root, 'plugins', id, 'tool-map.json');
  if (!existsSync(file)) return null;
  const p = products.products[id];
  const server = p.server?.name ?? id;
  const keyScopes = p.group === 'service-account' ? SERVICE_ACCOUNT_SCOPES_BY_SERVER[server] ?? [] : undefined;
  const prefix = `mcp__plugin_${id}_${server}__`;
  return JSON.parse(readFileSync(file, 'utf8')).filter((t) => registersEntry(t.name.startsWith(prefix) ? t.name.slice(prefix.length) : t.name, t.scopes, p.group, keyScopes)).length;
}

const apiTitle = new Map(catalog.apis.map((a) => [`${a.name}/${a.version}`, a]));
const methodsOf = (api, version) => apiTitle.get(`${api}/${version}`)?.methods.length ?? 0;

// Products table.
const productRows = [];
for (const [id, p] of Object.entries(products.products)) {
  const login = LOGIN[p.group] ?? { group: p.group, setup: '' };
  const built = toolCount(id);
  const gateway = (p.gateway ?? []).map((a) => `${a.api}/${a.version}`);
  const generated = (p.generated ?? []).map((a) => `${a.api}/${a.version}`);
  const methodsGateway = gateway.reduce((n, key) => n + (apiTitle.get(key)?.methods.length ?? 0), 0);
  productRows.push({
    id,
    title: p.title,
    group: login.group,
    setup: login.setup,
    tools: built ?? p.generatedToolCount,
    generatedApis: generated.length,
    gatewayApis: gateway.length,
    gatewayMethods: methodsGateway,
    curated: p.server?.curated ?? '',
    install: `claude plugin install ${id}@${marketplace.name}`,
  });
}

// CLI commands, read from the real help text so the document cannot drift from the code.
let helpText = '';
const cli = join(root, 'dist', 'cli', 'gsm.js');
if (existsSync(cli)) {
  try {
    helpText = execFileSync(process.execPath, [cli, '--help'], { encoding: 'utf8' });
  } catch (err) {
    helpText = String(err.stdout ?? '');
  }
}
const commandLines = helpText
  .split('\n')
  .filter((line) => /^ {2}\S/.test(line) && !line.startsWith('  --'))
  .map((line) => line.trim());

const unassigned = (products.unassigned ?? []).map((u) => `| ${u.api}${u.version ? `/${u.version}` : ''} | ${u.reason} |`);

const lines = [];
lines.push('# Surfaces');
lines.push('');
lines.push('Install with the simplest command: `npx google-services-mcps install --agent claude --plugin <id>` (see docs/TUTORIAL.md).');
lines.push('');
lines.push(
  `Generated by \`scripts/gen-surfaces.mjs\` from the repo state. ${productRows.length} products, ${catalog.apis.length} catalog entries, ${catalog.methodCount ?? '?'} catalogued methods, ${servers.servers.length} MCP servers.`,
);
lines.push('');
lines.push('## Products');
lines.push('');
lines.push('| Product (plugin) | Title | Login group | Tools | Gateway APIs (methods) | Install (Claude Code) |');
lines.push('|---|---|---|---|---|---|');
for (const r of productRows) {
  lines.push(`| \`${r.id}\` | ${r.title} | ${r.group} | ${r.tools} | ${r.gatewayApis} (${r.gatewayMethods}) | \`${r.install}\` |`);
}
lines.push('');
lines.push('## Login and setup per group');
lines.push('');
lines.push('| Group | Setup |');
lines.push('|---|---|');
for (const [group, text] of Object.entries(LOGIN)) lines.push(`| ${group} | ${text.setup} |`);
lines.push('');
lines.push('## Gateway tools (products with gateway APIs)');
lines.push('');
lines.push('Products with gateway APIs also expose `api_search`, `api_describe` and `api_call`, which reach those APIs. Calls classed as write or destructive go through the approval gate.');
lines.push('');
lines.push('## Command line (`gsm`)');
lines.push('');
lines.push('```');
// The published command is npx google-services-mcps; the repo's build prints node gsm.mjs.
lines.push((helpText.trim() || '(build the CLI first: npm run compile)').split('node gsm.mjs').join('npx google-services-mcps'));
lines.push('```');
lines.push('');
lines.push('Commands in the help text: ' + (commandLines.length ? commandLines.map((c) => c.split(' ')[0]).join(', ') : 'none found'));
lines.push('');
lines.push('## Catalog entries not assigned to a product');
lines.push('');
lines.push('| Entry | Reason |');
lines.push('|---|---|');
lines.push(...(unassigned.length ? unassigned : ['| (none) | |']));
lines.push('');
lines.push('## Sources');
lines.push('');
lines.push('- Products and placement: `config/products.json`');
lines.push('- Catalog: `data/catalog.json` (Google Discovery directory and direct discovery URLs)');
lines.push('- Tool counts: `plugins/<id>/tool-map.json` (built), counting the tools each server registers (`registersEntry` in `src/core/runtime-tools.ts`)');
lines.push('- Security model: `docs/SECURITY.md`; setup: `docs/SETUP.md`');
lines.push('');

const out = join(root, 'docs', 'SURFACES.md');
const text = lines.join('\n') + '\n';
if (process.argv.includes('--check')) {
  // Compared with line endings aside, so a checkout with CRLF files is not reported.
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : undefined;
  if (current !== text) {
    console.error('docs/SURFACES.md is out of date. Run: npm run surfaces');
    process.exit(1);
  }
  console.log(`docs/SURFACES.md is up to date: ${productRows.length} products, ${catalog.apis.length} catalog entries`);
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${out}: ${productRows.length} products, ${catalog.apis.length} catalog entries`);
}
