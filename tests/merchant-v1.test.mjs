// gmerchant on the Merchant API versions Google serves (1.35.2). Google discontinued Merchant API v1beta in May 2026
// ("The Merchant API v1beta version discontinued. All API calls must now be directed to the v1 or v1alpha versions.",
// https://developers.google.com/merchant/api/latest-updates) and lists Reviews only as v1alpha. The gateway moved from
// the 12 *_v1beta APIs to the same 12 *_v1 APIs, the generated Reviews tools from reviews_v1beta to reviews_v1alpha, and
// every merchantapi v1beta catalog entry is unassigned with that reason.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const readJson = (...parts) => JSON.parse(readFileSync(join(REPO, ...parts), 'utf8'));
const products = readJson('config', 'products.json');
const catalog = readJson('data', 'catalog.json');
const gmerchant = products.products.gmerchant;
const SUBS = ['accounts', 'conversions', 'datasources', 'inventories', 'issueresolution', 'lfp', 'notifications', 'ordertracking', 'products', 'promotions', 'quota', 'reports'];

test('gmerchant names no merchantapi v1beta version, generated or gateway', () => {
  const versions = [...gmerchant.generated, ...gmerchant.gateway].filter((e) => e.api === 'merchantapi').map((e) => e.version);
  assert.deepEqual(versions.filter((v) => v.endsWith('_v1beta')), []);
  assert.ok(gmerchant.generated.some((e) => e.api === 'merchantapi' && e.version === 'reviews_v1alpha'), 'Reviews is generated from v1alpha');
});

test('the gateway is the 12 v1 APIs that replaced its v1beta APIs, each also generated by gmerchant', () => {
  assert.deepEqual(
    gmerchant.gateway.map((e) => `${e.api}:${e.version}`),
    SUBS.map((s) => `merchantapi:${s}_v1`),
  );
  for (const e of gmerchant.gateway) assert.ok(gmerchant.generated.some((g) => g.api === e.api && g.version === e.version && !g.include), `${e.version} is a whole generated entry`);
});

test('every merchantapi v1beta catalog entry is unassigned, with the discontinuation as its reason', () => {
  const beta = catalog.apis.filter((a) => a.name === 'merchantapi' && a.version.endsWith('_v1beta')).map((a) => a.version).sort();
  assert.deepEqual(beta, [...SUBS, 'reviews'].map((s) => `${s}_v1beta`).sort());
  for (const version of beta) {
    const u = products.unassigned.find((x) => x.api === 'merchantapi' && x.version === version);
    assert.ok(u, `${version} is unassigned`);
    assert.match(u.reason, /discontinued Merchant API v1beta in May 2026/, version);
  }
  // The one v1beta method without a v1 counterpart is named in the reason, so it is a recorded loss, not a silent one.
  const accounts = products.unassigned.find((x) => x.api === 'merchantapi' && x.version === 'accounts_v1beta');
  assert.match(accounts.reason, /onlineReturnPolicies\.patch exists only here/);
});

test('Reviews v1alpha is a supplemental catalog entry with its own Discovery URL and the same 8 methods as v1beta', () => {
  const alpha = catalog.apis.find((a) => a.name === 'merchantapi' && a.version === 'reviews_v1alpha');
  const beta = catalog.apis.find((a) => a.name === 'merchantapi' && a.version === 'reviews_v1beta');
  assert.ok(alpha, 'reviews_v1alpha is in the catalog');
  assert.equal(alpha.discoveryRestUrl, 'https://merchantapi.googleapis.com/$discovery/rest?version=reviews_v1alpha');
  assert.equal(alpha.preferred, false);
  assert.deepEqual(alpha.methods.map((m) => m[0]).sort(), beta.methods.map((m) => m[0]).sort());
  for (const m of alpha.methods) assert.match(m[2], /^reviews\/v1alpha\//, m[0]);
  const script = readFileSync(join(REPO, 'scripts', 'build-catalog.mjs'), 'utf8');
  assert.match(script, /version: 'reviews_v1alpha'/, 'SUPPLEMENTAL_ENTRIES lists it');
});

test('the built plugin: the v1alpha snapshot, the v1 gateway catalog, and no v1beta-only gateway method', () => {
  const dir = join(REPO, 'plugins', 'gmerchant');
  assert.ok(existsSync(join(dir, 'discovery', 'merchantapi.reviews_v1alpha.json')));
  assert.equal(existsSync(join(dir, 'discovery', 'merchantapi.reviews_v1beta.json')), false);
  const subset = JSON.parse(readFileSync(join(dir, 'catalog.json'), 'utf8'));
  assert.deepEqual(subset.apis.map((a) => a.version).sort(), SUBS.map((s) => `${s}_v1`).sort());
  const kinds = JSON.parse(readFileSync(join(dir, 'method-kinds.json'), 'utf8'));
  assert.equal(kinds['merchantapi.accounts.onlineReturnPolicies.patch'], undefined, 'v1beta only, discontinued');
  assert.equal(kinds['merchantapi.accounts.regions.batchDelete'], 'destructive', 'a v1 method the gateway reaches now');
  const servers = JSON.parse(readFileSync(join(dir, 'servers.json'), 'utf8')).servers[0];
  assert.deepEqual(servers.gatewayApis, gmerchant.gateway);
  const label = servers.label;
  assert.doesNotMatch(label, /Manufacturer Center/, 'the description no longer claims Manufacturer Center');
});
