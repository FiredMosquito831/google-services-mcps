/**
 * Tool definitions for the Google Ads server (MCP name "gads").
 *
 * The curated tools here use the Google Ads REST API directly. The version is ADS_API_VERSION: v26, the newest
 * version that answers the discovery document (https://googleads.googleapis.com/$discovery/rest?version=v26).
 * The same API is also generated as per-method tools and gateway methods (config/products.json).
 *
 * Tools:
 *   ads_list_customers  read     customers:listAccessibleCustomers
 *   ads_search          read     googleAds:search, one page of GAQL. Must be a SELECT. At most 500 rows returned.
 *   ads_mutate          dynamic  googleAds:mutate. The kind comes from the body (core/dynamic.ts): validate_only
 *                                (default true) is a read with no gate. Otherwise the gate runs first: write, or
 *                                destructive when an operation removes a resource.
 *
 * Auth: the OAuth user token of the business group (gsm login business), with the adwords scope. The Cloud project
 * of that OAuth client is what Google Ads grants access to. A developer token is no longer required. When one is
 * set (GSM_ADS_DEVELOPER_TOKEN, or the developerToken field of <tokenDir>/ads.json, mode 0600), it is sent in the
 * developer-token header, which Google ignores. GSM_ADS_LOGIN_CUSTOMER_ID is the optional manager account ID, sent
 * when set. The headers and the redaction are in core/ads.ts, shared with the generic request path. A token is
 * never printed or logged, and it is removed from any error text.
 *
 * The server entry is generated by scripts/bundle.mjs. buildTools makes no network call.
 */
import type { JWT, OAuth2Client } from 'google-auth-library';
import { z } from 'zod';
import type { RuntimeConfig } from '../core/config.js';
import { getAuthClient, googleScopes } from '../core/auth.js';
import { adsHeaders, redactSecret } from '../core/ads.js';
import { curatedMutateBody, GOOGLE_ADS_MUTATE_METHOD, operationsRisk, resolveDynamicKind } from '../core/dynamic.js';
import { defineTool, type ActionKind, type ToolDef } from '../core/tools.js';

/** The Google Ads REST API version. v26 is the newest that answers the discovery document. */
export const ADS_API_VERSION = 'v26';
const ADS_BASE = `https://googleads.googleapis.com/${ADS_API_VERSION}`;
const ADS_SCOPES = googleScopes('adwords');

/** The Discovery method id of googleAds:mutate (defined in core/dynamic.ts, where the hook can read it too). */
export { GOOGLE_ADS_MUTATE_METHOD };

const SEARCH_DEFAULT_PAGE = 1000;
const SEARCH_MAX_PAGE = 10_000;
const SEARCH_MAX_QUERY = 10_000;
const SEARCH_ROW_CAP = 500;

type Auth = OAuth2Client | JWT;
type Operation = Record<string, unknown>;

interface AdsCustomersResponse {
  resourceNames?: string[];
}
interface AdsSearchResponse {
  results?: unknown[];
  nextPageToken?: string;
}
interface AdsMutateResponse {
  mutateOperationResponses?: unknown[];
  requestId?: string;
}

const authClients = new Map<string, Auth>();

/** The OAuth client of the business group, built once per token directory. A failed login is not kept, so a new login is seen. */
async function authFor(cfg: RuntimeConfig): Promise<Auth> {
  const cached = authClients.get(cfg.tokenDir);
  if (cached) return cached;
  const auth = await getAuthClient('business', cfg);
  authClients.set(cfg.tokenDir, auth);
  return auth;
}

interface AdsErrorBody {
  code?: number;
  message?: string;
  status?: string;
  details?: Array<{ errors?: Array<{ message?: string; errorCode?: Record<string, string> }> }>;
}

/**
 * Google's error as a plain Error. The reason is the status name (INVALID_ARGUMENT, PERMISSION_DENIED
 * and so on), and the GoogleAdsFailure details add their specific error codes. describeError reads
 * code, reason and message from it.
 */
export function adsError(err: unknown, secret: string): Error {
  const e = err as { message?: string; response?: { status?: number; data?: { error?: AdsErrorBody } } };
  const body = e.response?.data?.error;
  const status = e.response?.status;
  if (!body?.message) {
    return Object.assign(new Error(redactSecret(e.message ?? 'Google Ads request failed', secret)), { code: status });
  }
  const details = (body.details ?? [])
    .flatMap((d) => d.errors ?? [])
    .map((f) => {
      const codes = Object.entries(f.errorCode ?? {})
        .map(([key, value]) => `${key}: ${value}`)
        .join(', ');
      return [f.message, codes ? `(${codes})` : ''].filter(Boolean).join(' ');
    })
    .filter(Boolean);
  const message = [body.message, ...details].join(' ');
  return Object.assign(new Error(redactSecret(message, secret)), {
    code: status ?? body.code,
    errors: [{ reason: body.status ?? 'UNKNOWN' }],
  });
}

interface AdsCall {
  method: 'GET' | 'POST';
  /** The path after the version, such as customers/1234567890/googleAds:search. */
  path: string;
  body?: unknown;
}

interface AdsSession {
  request<T>(call: AdsCall): Promise<T>;
}

/**
 * The session for a sequence of calls: the OAuth client, and the Ads headers. The developer-token header is sent only
 * when a token is configured, and a missing token blocks nothing. Each request goes through requestWithRetry.
 */
async function adsSession(cfg: RuntimeConfig): Promise<AdsSession> {
  const headers = adsHeaders(cfg);
  const secret = headers['developer-token'] ?? '';
  const auth = await authFor(cfg);
  return {
    async request<T>(call: AdsCall): Promise<T> {
      try {
        // The auth client retries each request (core/auth.ts), so this call is covered.
        const res = await auth.request<T>({ url: `${ADS_BASE}/${call.path}`, method: call.method, data: call.body, headers });
        return res.data;
      } catch (err) {
        throw adsError(err, secret);
      }
    },
  };
}

/** GAQL reads only: the query must be a SELECT. Checked before any request is sent. */
export function assertSelectQuery(query: string): void {
  if (!/^select\s/i.test(query.trimStart())) {
    throw new Error('ads_search takes one GAQL SELECT query. Any other statement is refused before a request is sent.');
  }
}

/** The resource key and body of one mutate operation: exactly one key, ending in Operation, with an object value. */
export function resourceOperation(op: Operation): { key: string; body: Record<string, unknown> } {
  const keys = Object.keys(op);
  const key = keys[0];
  const body = key === undefined ? undefined : op[key];
  if (keys.length !== 1 || key === undefined || !key.endsWith('Operation') || typeof body !== 'object' || body === null || Array.isArray(body)) {
    throw new Error(
      `Each operation needs exactly one resource key ending in Operation, with an object value, such as {"campaignOperation": {"create": {...}}}. Got: ${keys.join(', ') || 'no keys'}.`,
    );
  }
  return { key, body: body as Record<string, unknown> };
}

/**
 * Risk of a list of operations: destructive when one operation removes, else write. Same rule as the
 * dynamic kind in core/dynamic.ts, which ads_mutate and the generic tools use.
 */
export function riskOfOperations(operations: Operation[]): ActionKind {
  return operationsRisk(operations);
}

const customerId = z
  .string()
  .regex(/^\d+$/, 'Use digits only, with no dashes.')
  .describe('Customer ID, digits only, for example 1234567890 (no dashes). ads_list_customers lists them.');

const searchShape = {
  customer_id: customerId,
  query: z
    .string()
    .max(SEARCH_MAX_QUERY)
    .describe('A GAQL query that starts with SELECT, for example "SELECT campaign.id, campaign.name FROM campaign". At most 10000 characters.'),
  page_size: z
    .number()
    .int()
    .min(1)
    .max(SEARCH_MAX_PAGE)
    .optional()
    .describe(`Rows to ask Google for, 1 to ${SEARCH_MAX_PAGE}. Default ${SEARCH_DEFAULT_PAGE}. At most ${SEARCH_ROW_CAP} rows are returned.`),
};

const mutateShape = {
  customer_id: customerId,
  operations: z
    .array(z.record(z.string(), z.unknown()))
    .min(1)
    .describe(
      'Mutate operations, as Google defines them. Each is an object with exactly one resource key, such as {"campaignOperation": {"create": {...}}}, {"adGroupOperation": {"update": {...}, "updateMask": "name"}} or {"campaignOperation": {"remove": "customers/1234567890/campaigns/9"}}.',
    ),
  validate_only: z
    .boolean()
    .optional()
    .describe('Default true: Google checks the operations and changes nothing. Set false to apply them, which asks the user to approve the exact operations first.'),
};

/** Tool definitions for the gads server: the Google Ads REST API with the business group's OAuth token. */
export async function buildTools(cfg: RuntimeConfig): Promise<ToolDef[]> {
  return [
    defineTool({
      name: 'ads_list_customers',
      title: 'List Google Ads accounts',
      description:
        'List the Google Ads customer accounts the logged-in user can access, as resource names such as customers/1234567890. The digits are the customer_id for the other ads tools.',
      kind: 'read',
      scopes: ADS_SCOPES,
      inputSchema: {},
      async handler() {
        const session = await adsSession(cfg);
        const res = await session.request<AdsCustomersResponse>({ method: 'GET', path: 'customers:listAccessibleCustomers' });
        return { resourceNames: res.resourceNames ?? [] };
      },
    }),
    defineTool({
      name: 'ads_search',
      title: 'Search Google Ads (GAQL)',
      description:
        'Run one page of a GAQL SELECT query against a Google Ads account and return the rows, at most 500. Read only: any statement other than SELECT is refused before a request is sent.',
      kind: 'read',
      scopes: ADS_SCOPES,
      inputSchema: searchShape,
      async handler(args) {
        const input = z.object(searchShape).parse(args);
        assertSelectQuery(input.query);
        const session = await adsSession(cfg);
        const res = await session.request<AdsSearchResponse>({
          method: 'POST',
          path: `customers/${input.customer_id}/googleAds:search`,
          body: { query: input.query, pageSize: input.page_size ?? SEARCH_DEFAULT_PAGE },
        });
        const rows = res.results ?? [];
        const truncated = rows.length > SEARCH_ROW_CAP;
        return {
          rowCount: Math.min(rows.length, SEARCH_ROW_CAP),
          results: rows.slice(0, SEARCH_ROW_CAP),
          ...(truncated
            ? { truncated: true, note: `Google returned ${rows.length} rows on this page. Only the first ${SEARCH_ROW_CAP} are shown; narrow the query to see fewer rows.` }
            : {}),
          ...(res.nextPageToken && !truncated ? { note: 'Google has more pages for this query. This tool returns only the first page.' } : {}),
        };
      },
    }),
    defineTool({
      name: 'ads_mutate',
      title: 'Change Google Ads resources',
      description:
        'Create, update or remove Google Ads resources in one mutate request. Each operation has exactly one resource key (campaignOperation, adGroupOperation, campaignBudgetOperation and so on) holding create, update (with updateMask) or remove. validate_only defaults to true: Google checks the operations and nothing changes. With validate_only false the user approves the exact operations first, and a remove operation is destructive.',
      // No methodId in the tool map. The hook classifies this tool's arguments with curatedMutateBody, the same
      // normalisation the gate below uses, so a validate-only call is not asked for and a change is.
      kind: 'dynamic',
      scopes: ADS_SCOPES,
      inputSchema: mutateShape,
      async handler(args, ctx) {
        const input = z.object(mutateShape).parse(args);
        const operations = input.operations;
        for (const op of operations) resourceOperation(op);
        // validate_only is read as validateOnly by curatedMutateBody (default true): the same normalisation the hook uses.
        const mutate = curatedMutateBody({ operations, validate_only: input.validate_only });
        const body = { mutateOperations: mutate.operations, validateOnly: mutate.validateOnly };
        const session = await adsSession(cfg);
        // The same rule as the generated and gateway mutate methods (core/dynamic.ts): a validate-only call is a read.
        const kind = resolveDynamicKind(GOOGLE_ADS_MUTATE_METHOD, mutate) ?? 'destructive';
        if (kind !== 'read') {
          await ctx.gate({ kind, target: 'ads_mutate', methodId: GOOGLE_ADS_MUTATE_METHOD, args: input });
        }
        const res = await session.request<AdsMutateResponse>({
          method: 'POST',
          path: `customers/${input.customer_id}/googleAds:mutate`,
          body,
        });
        return mutate.validateOnly ? { validateOnly: true, note: 'Nothing was changed. Google checked these operations.', ...res } : res;
      },
    }),
  ];
}
