import { getAuthClient, googleScopes } from '../core/auth.js';
import { adsHeaders, redactSecret } from '../core/ads.js';
import { curatedMutateBody, GOOGLE_ADS_MUTATE_METHOD, operationsRisk, resolveDynamicKind } from '../core/dynamic.js';
import { defineTool, type ActionKind, type ToolDef } from '../core/tools.js';
import { fitItems } from '../core/result-shape.js';

/** The Google Ads REST API version. v26 is the newest that answers the discovery document. */
export const ADS_API_VERSION = 'v26';
const ADS_BASE = `https://googleads.googleapis.com/${ADS_API_VERSION}`;
const ADS_SCOPES = googleScopes('adwords');

/** The Discovery method id of googleAds:mutate (defined in core/dynamic.ts, where the hook can read it too). */
export { GOOGLE_ADS_MUTATE_METHOD };

const SEARCH_MAX_QUERY = 10_000;
const SEARCH_ROW_CAP = 500;

type Auth = OAuth2Client | JWT;
type Operation = Record<string, unknown>;

interface AdsCustomersResponse {
  resourceNames?: string[];
}
interface AdsSearchResponse {
  results?: unknown[];
  nextPageToken?: string;
}
interface AdsMutateResponse {
  mutateOperationResponses?: unknown[];
  requestId?: string;
}
interface AdsField {
  name?: string;
  category?: string;
  selectable?: boolean;
  filterable?: boolean;
  sortable?: boolean;
}
interface AdsFieldsResponse {
  results?: AdsField[];
  nextPageToken?: string;
}

/** The OAuth client of the business group, for the account the call names (see account-context.ts). */
async function authFor(cfg: RuntimeConfig): Promise<Auth> {
  return getAuthClient('business', cfg);
}

interface AdsErrorBody {
  code?: number;
  message?: string;
  status?: string;
  details?: Array<{ errors?: Array<{ message?: string; errorCode?: Record<string, string> }> }>;
}

/**
 * Google's error as a plain Error. The reason is the status name (INVALID_ARGUMENT, PERMISSION_DENIED
 * and so on), and the GoogleAdsFailure details add their specific error codes. describeError reads
 * code, reason and message from it.
 */
export function adsError(err: unknown, secret: string): Error {
  const e = err as { message?: string; response?: { status?: number; data?: { error?: AdsErrorBody } } };
  const body = e.response?.data?.error;
  const status = e.response?.status;
  if (!body?.message) {
    return Object.assign(new Error(redactSecret(e.message ?? 'Google Ads request failed', secret)), { code: status });
  }
  const details = (body.details ?? [])
    .flatMap((d) => d.errors ?? [])
    .map((f) => {
      const codes = Object.entries(f.errorCode ?? {})
        .map(([key, value]) => `${key}: ${value}`)
        .join(', ');
      return [f.message, codes ? `(${codes})` : ''].filter(Boolean).join(' ');
    })
    .filter(Boolean);
  const message = [body.message, ...details].join(' ');
  return Object.assign(new Error(redactSecret(message, secret)), {
    code: status ?? body.code,
    errors: [{ reason: body.status ?? 'UNKNOWN' }],
  });
}

interface AdsCall {
  method: 'GET' | 'POST';
  /** The path after the version, such as customers/1234567890/googleAds:search. */
  path: string;
  body?: unknown;
}

interface AdsSession {
  request<T>(call: AdsCall): Promise<T>;
}

/**
 * The session for a sequence of calls: the OAuth client, and the Ads headers. The developer-token header is sent only
 * when a token is configured, and a missing token blocks nothing. Each request goes through requestWithRetry.
 */
async function adsSession(cfg: RuntimeConfig): Promise<AdsSession> {
  const headers = adsHeaders(cfg);
  const secret = headers['developer-token'] ?? '';
  const auth = await authFor(cfg);
  return {
    async request<T>(call: AdsCall): Promise<T> {
      try {
        // The auth client retries each request (core/auth.ts), so this call is covered.
        const res = await auth.request<T>({ url: `${ADS_BASE}/${call.path}`, method: call.method, data: call.body, headers });
        return res.data;
      } catch (err) {
        throw adsError(err, secret);
      }
    },
  };
}

/** GAQL reads only: the query must be a SELECT. Checked before any request is sent. */
export function assertSelectQuery(query: string): void {
  if (!/^select\s/i.test(query.trimStart())) {
    throw new Error('ads_search takes one GAQL SELECT query. Any other statement is refused before a request is sent.');
  }
}

/** A GAQL resource name, as in the FROM clause: campaign, ad_group, ad_group_criterion. */
const RESOURCE_NAME = /^[a-z][a-z0-9_]*$/;
/** A GAQL field name: a resource, metrics or segments, then one or more parts, such as campaign.id or ad_group_criterion.keyword.text. */
const FIELD_NAME = /^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+$/;
/** One ORDER BY item: a field name, optionally ASC or DESC. */
const ORDERING = /^([a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+)(?:\s+(asc|desc))?$/i;
/**
 * Clause words a condition may not hold outside a quoted value, so each condition stays one condition of the WHERE
 * clause. A part of a dotted field name (campaign.limit_x, x.order) is not a clause word.
 */
const CLAUSE_WORDS = /(?:^|[^.\w])(select|from|where|order|limit|parameters)(?![\w.])/i;

/** Checks a resource name for the FROM clause or a field lookup. Throws before any request is sent. */
export function assertResourceName(resource: string): void {
  if (!RESOURCE_NAME.test(resource)) {
    throw new Error(`"${resource}" is not a Google Ads resource name: use lowercase letters, digits and underscores, such as campaign or ad_group.`);
  }
}

/**
 * The text of a condition outside its quoted values. Values in single or double quotes may hold any character (a
 * backslash escapes the next one). An unclosed quote is refused: the rest of the query would become part of a value.
 */
function unquoted(condition: string): string {
  let out = '';
  let quote: string | undefined;
  for (let i = 0; i < condition.length; i++) {
    const ch = condition[i] as string;
    if (quote) {
      if (ch === '\\') i++;
      else if (ch === quote) {
        quote = undefined;
        out += ' ';
      }
      continue;
    }
    if (ch === "'" || ch === '"') quote = ch;
    else out += ch;
  }
  if (quote) throw new Error(`The condition ${JSON.stringify(condition)} has a quote that is not closed.`);
  return out;
}

/** Checks one WHERE condition: no clause words or semicolons outside quoted values, and closed quotes. */
export function assertCondition(condition: string): void {
  const rest = unquoted(condition);
  if (rest.trim() === '') throw new Error('A condition is empty.');
  if (rest.includes(';')) throw new Error(`The condition ${JSON.stringify(condition)} holds a semicolon outside a quoted value.`);
  const word = CLAUSE_WORDS.exec(rest);
  if (word) {
    throw new Error(
      `The condition ${JSON.stringify(condition)} holds ${word[1]?.toUpperCase()} outside a quoted value. Give each condition alone; use orderings and limit for ORDER BY and LIMIT.`,
    );
  }
}

/** The structured form of a GAQL query (matches the arguments of search in Google's Google Ads MCP server). */
export interface GaqlParts {
  fields: string[];
  resource: string;
  conditions?: string[];
  orderings?: string[];
  limit?: number;
}

/**
 * Writes a GAQL SELECT from checked parts: SELECT <fields> FROM <resource> [WHERE c1 AND c2] [ORDER BY o1, o2]
 * [LIMIT n] PARAMETERS omit_unselected_resource_names=true, the form Google's Google Ads MCP server builds. Field and
 * resource names must be plain names; conditions are checked by assertCondition. Throws before any request is sent.
 */
export function buildGaql(parts: GaqlParts): string {
  assertResourceName(parts.resource);
  const fields = [...new Set(parts.fields.map((f) => f.trim()))];
  if (fields.length === 0) throw new Error('fields needs at least one field, such as campaign.id.');
  for (const field of fields) {
    if (!FIELD_NAME.test(field)) throw new Error(`"${field}" is not a GAQL field name, such as campaign.id, metrics.clicks or segments.date.`);
  }
  const conditions = (parts.conditions ?? []).map((c) => c.trim());
  for (const condition of conditions) assertCondition(condition);
  const orderings = (parts.orderings ?? []).map((o) => {
    const match = ORDERING.exec(o.trim());
    if (!match) throw new Error(`"${o}" is not an ordering: use a field name, optionally followed by ASC or DESC, such as metrics.clicks DESC.`);
    return match[2] ? `${match[1]} ${match[2].toUpperCase()}` : (match[1] as string);
  });
  if (parts.limit !== undefined && (!Number.isInteger(parts.limit) || parts.limit < 1)) throw new Error('limit must be a whole number of 1 or more.');
  return [
    `SELECT ${fields.join(', ')} FROM ${parts.resource}`,
    conditions.length ? ` WHERE ${conditions.join(' AND ')}` : '',
    orderings.length ? ` ORDER BY ${orderings.join(', ')}` : '',
    parts.limit !== undefined ? ` LIMIT ${parts.limit}` : '',
    ' PARAMETERS omit_unselected_resource_names=true',
  ].join('');
}

/** The GAQL of one ads_search call: the query as given, or one built from the parts. Exactly one form. */
export function searchQueryOf(input: { query?: string; fields?: string[]; resource?: string; conditions?: string[]; orderings?: string[]; limit?: number }): string {
  const structured = input.fields !== undefined || input.resource !== undefined;
  const partsOnly = input.conditions !== undefined || input.orderings !== undefined || input.limit !== undefined;
  if (input.query !== undefined) {
    if (structured || partsOnly) throw new Error('Give either query, or fields and resource (with conditions, orderings and limit), not both.');
    return input.query;
  }
  if (!input.fields || !input.resource) {
    throw new Error('Give query (a GAQL SELECT), or fields and resource. ads_resource_metadata lists the fields of a resource.');
  }
  return buildGaql({ fields: input.fields, resource: input.resource, conditions: input.conditions, orderings: input.orderings, limit: input.limit });
}

/**
 * The GoogleAdsField query language of googleAdsFields:search takes no FROM clause. The two queries Google's
 * get_resource_metadata runs: the resource's own attributes, and every field that is selectable with the resource
 * (its metrics, its segments and the attributes of the resources it is attributed to).
 */
export function resourceMetadataQueries(resource: string): [string, string] {
  assertResourceName(resource);
  return [
    `SELECT name, category, selectable, filterable, sortable WHERE name LIKE '${resource}.%' AND category = 'ATTRIBUTE'`,
    `SELECT name, category, selectable, filterable, sortable WHERE selectable_with CONTAINS ANY('${resource}')`,
  ];
}

/** Pages of googleAdsFields:search followed at most, per query: a guard against an endless page loop. The answer says when it stopped there. */
const FIELD_PAGES_MAX = 50;

/** The resource key and body of one mutate operation: exactly one key, ending in Operation, with an object value. */
export function resourceOperation(op: Operation): { key: string; body: Record<string, unknown> } {
  const keys = Object.keys(op);
  const key = keys[0];
  const body = key === undefined ? undefined : op[key];
  if (keys.length !== 1 || key === undefined || !key.endsWith('Operation') || typeof body !== 'object' || body === null || Array.isArray(body)) {
    throw new Error(
      `Each operation needs exactly one resource key ending in Operation, with an object value, such as {"campaignOperation": {"create": {...}}}. Got: ${keys.join(', ') || 'no keys'}.`,
    );
  }
  return { key, body: body as Record<string, unknown> };
}

/**
 * Risk of a list of operations: destructive when one operation removes, else write. Same rule as the
 * dynamic kind in core/dynamic.ts, which ads_mutate and the generic tools use.
 */
export function riskOfOperations(operations: Operation[]): ActionKind {
  return operationsRisk(operations);
}

const customerId = z
  .string()
  .regex(/^\d+$/, 'Use digits only, with no dashes.')
  .describe('Customer ID, digits only, for example 1234567890 (no dashes). ads_list_customers lists them.');

const searchShape = {
  customer_id: customerId,
  query: z
    .string()
    .max(SEARCH_MAX_QUERY)
    .optional()
    .describe(
      'A GAQL query that starts with SELECT, for example "SELECT campaign.id, campaign.name FROM campaign". At most 10000 characters. Give this, or fields and resource.',
    ),
  fields: z
    .array(z.string())
    .min(1)
    .optional()
    .describe('Structured form: the fields to select, such as ["campaign.id", "campaign.name", "metrics.clicks"]. Needs resource.'),
  resource: z.string().optional().describe('Structured form: the resource of the FROM clause, such as campaign or ad_group.'),
  conditions: z
    .array(z.string())
    .optional()
    .describe(
      `Structured form: WHERE conditions, joined with AND, such as ["campaign.status = 'ENABLED'", "segments.date DURING LAST_30_DAYS"]. One condition each; quoted values may hold any text.`,
    ),
  orderings: z.array(z.string()).optional().describe('Structured form: ORDER BY items, such as ["metrics.clicks DESC"].'),
  limit: z.number().int().min(1).optional().describe('Structured form: LIMIT, the most rows Google returns. This tool shows at most 500 rows of a page.'),
  page_token: z
    .string()
    .optional()
    .describe('next_page_token of the previous answer, with the same query: the next page of rows (Google Ads sets the page size).'),
};

const metadataShape = {
  resource: z.string().describe('A Google Ads resource name, as in a FROM clause: campaign, ad_group, ad_group_criterion, keyword_view and so on.'),
};

const mutateShape = {
  customer_id: customerId,
  operations: z
    .array(z.record(z.string(), z.unknown()))
    .min(1)
    .describe(
      'Mutate operations, as Google defines them. Each is an object with exactly one resource key, such as {"campaignOperation": {"create": {...}}}, {"adGroupOperation": {"update": {...}, "updateMask": "name"}} or {"campaignOperation": {"remove": "customers/1234567890/campaigns/9"}}.',
    ),
  validate_only: z
    .boolean()
    .optional()
    .describe('Default true: Google checks the operations and changes nothing. Set false to apply them, which asks the user to approve the exact operations first.'),
};

/** Tool definitions for the gads server: the Google Ads REST API with the business group's OAuth token. */
export async function buildTools(cfg: RuntimeConfig): Promise<ToolDef[]> {
  return [
    defineTool({
      name: 'ads_list_customers',
      title: 'List Google Ads accounts',
      description:
        'List the Google Ads customer accounts the logged-in user can access, as resource names such as customers/1234567890. The digits are the customer_id for the other ads tools.',
      kind: 'read',
      scopes: ADS_SCOPES,
      inputSchema: {},
      async handler() {
        const session = await adsSession(cfg);
        const res = await session.request<AdsCustomersResponse>({ method: 'GET', path: 'customers:listAccessibleCustomers' });
        return { resourceNames: res.resourceNames ?? [] };
      },
    }),
    defineTool({
      name: 'ads_search',
      title: 'Search Google Ads (GAQL)',
      description:
        "Run one page of a GAQL SELECT query against a Google Ads account and return the rows, at most 500 and at most what fits the result limit (matches search in Google's Google Ads MCP server). Give the query as text, or as fields, resource, conditions, orderings and limit, from which the SELECT is written (with PARAMETERS omit_unselected_resource_names=true, as Google's server does). next_page_token, with page_token, reads the next page. Google Ads has no row offset, so rows left out of a page are reached by narrowing the query (a WHERE condition, fewer fields or a LIMIT). ads_resource_metadata lists the fields a resource can select, filter and sort by. Read only: any statement other than SELECT is refused before a request is sent.",
      kind: 'read',
      scopes: ADS_SCOPES,
      inputSchema: searchShape,
      async handler(args) {
        const input = z.object(searchShape).parse(args);
        const query = searchQueryOf(input);
        assertSelectQuery(query);
        if (query.length > SEARCH_MAX_QUERY) throw new Error(`The query is ${query.length} characters; at most ${SEARCH_MAX_QUERY} are sent.`);
        const session = await adsSession(cfg);
        const res = await session.request<AdsSearchResponse>({
          method: 'POST',
          path: `customers/${input.customer_id}/googleAds:search`,
          // No pageSize: Google Ads (v26 Discovery) answers PAGE_SIZE_NOT_SUPPORTED when it is set. Google sets the page size.
          body: { query, ...(input.page_token ? { pageToken: input.page_token } : {}) },
        });
        const rows = res.results ?? [];
        const truncated = rows.length > SEARCH_ROW_CAP;
        const next = res.nextPageToken || undefined;
        const answer = {
          ...(next ? { next_page_token: next } : {}),
          // The SELECT written from the parts, so the caller can see and reuse it. A query given as text is not repeated.
          ...(input.query === undefined ? { query } : {}),
          rowCount: Math.min(rows.length, SEARCH_ROW_CAP),
          results: rows.slice(0, SEARCH_ROW_CAP),
          ...(truncated
            ? {
                truncated: true,
                note: `Google returned ${rows.length} rows on this page. Only the first ${SEARCH_ROW_CAP} are shown; narrow the query to see fewer rows.${next ? ' next_page_token continues after this whole page.' : ''}`,
              }
            : {}),
          ...(next && !truncated ? { note: 'Google has more pages for this query: call again with page_token set to next_page_token.' } : {}),
        };
        // Rows that do not fit the result limit are left out at the end; rowCount then counts the rows shown.
        return fitItems(answer, 'results', cfg.maxResultChars, (shown) => ({
          fields: { rowCount: shown },
          how_to_continue: `Google returned ${rows.length} rows on this page; the first ${shown} fit the result limit (${cfg.maxResultChars} characters). Google Ads has no row offset: to see the others, narrow the query (a WHERE condition, fewer fields or a LIMIT).${next ? ' next_page_token continues after this whole page, not after the rows shown.' : ''}`,
        }));
      },
    }),
    defineTool({
      name: 'ads_resource_metadata',
      title: 'Fields of a Google Ads resource',
      description:
        "List the fields a Google Ads resource can select, filter by and sort by in GAQL: its own attributes, and the metrics, segments and attributed-resource fields that are selectable with it (matches get_resource_metadata in Google's Google Ads MCP server). Use it before ads_search to pick valid fields. Needs no customer_id: the field catalog is the same for every account.",
      kind: 'read',
      scopes: ADS_SCOPES,
      inputSchema: metadataShape,
      async handler(args) {
        const { resource } = z.object(metadataShape).parse(args);
        const queries = resourceMetadataQueries(resource);
        const session = await adsSession(cfg);
        const fields = new Map<string, AdsField>();
        let stoppedEarly = false;
        for (const query of queries) {
          let pageToken: string | undefined;
          let pages = 0;
          do {
            const res = await session.request<AdsFieldsResponse>({
              method: 'POST',
              path: 'googleAdsFields:search',
              body: { query, ...(pageToken ? { pageToken } : {}) },
            });
            for (const f of res.results ?? []) if (f.name && !fields.has(f.name)) fields.set(f.name, f);
            pageToken = res.nextPageToken || undefined;
            pages += 1;
          } while (pageToken && pages < FIELD_PAGES_MAX);
          if (pageToken) stoppedEarly = true;
        }
        const list = [...fields.values()];
        const names = (keep: (f: AdsField) => boolean) => list.filter(keep).map((f) => f.name as string);
        return {
          resource,
          selectable: names((f) => f.selectable === true),
          filterable: names((f) => f.filterable === true),
          sortable: names((f) => f.sortable === true),
          ...(list.length === 0
            ? { note: `Google returned no fields for "${resource}". Check the resource name: it is the name used in a FROM clause, such as campaign or ad_group.` }
            : {}),
          ...(stoppedEarly ? { truncated: true, note: `Google had more than ${FIELD_PAGES_MAX} pages of fields; only those pages are shown.` } : {}),
        };
      },
    }),
    defineTool({
      name: 'ads_mutate',
      title: 'Change Google Ads resources',
      description:
        'Create, update or remove Google Ads resources in one mutate request. Each operation has exactly one resource key (campaignOperation, adGroupOperation, campaignBudgetOperation and so on) holding create, update (with updateMask) or remove. validate_only defaults to true: Google checks the operations and nothing changes. With validate_only false the user approves the exact operations first, and a remove operation is destructive.',
      // No methodId in the tool map. The hook classifies this tool's arguments with curatedMutateBody, the same
      // normalisation the gate below uses, so a validate-only call is not asked for and a change is.
      kind: 'dynamic',
      scopes: ADS_SCOPES,
      inputSchema: mutateShape,
      async handler(args, ctx) {
        const input = z.object(mutateShape).parse(args);
        const operations = input.operations;
        for (const op of operations) resourceOperation(op);
        // validate_only is read as validateOnly by curatedMutateBody (default true): the same normalisation the hook uses.
        const mutate = curatedMutateBody({ operations, validate_only: input.validate_only });
        const body = { mutateOperations: mutate.operations, validateOnly: mutate.validateOnly };
        const session = await adsSession(cfg);
        // The same rule as the generated and gateway mutate methods (core/dynamic.ts): a validate-only call is a read.
        const kind = resolveDynamicKind(GOOGLE_ADS_MUTATE_METHOD, mutate) ?? 'destructive';
        if (kind !== 'read') {
          await ctx.gate({ kind, target: 'ads_mutate', methodId: GOOGLE_ADS_MUTATE_METHOD, args: input });
        }
        const res = await session.request<AdsMutateResponse>({
          method: 'POST',
          path: `customers/${input.customer_id}/googleAds:mutate`,
          body,
        });
        return mutate.validateOnly ? { validateOnly: true, note: 'Nothing was changed. Google checked these operations.', ...res } : res;
      },
    }),
  ];
}
